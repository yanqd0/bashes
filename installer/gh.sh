#!/usr/bin/env bash
#
# gh 安装脚本
# GitHub CLI — GitHub 官方命令行客户端
# 通过 wget 下载 GitHub Release 预编译二进制，安装到 ~/bin/
#
# 使用方式：
#   installer gh                        # 自动检测最新版本并安装
#   GH_VERSION=v2.80.0 installer gh     # 指定版本安装（跳过版本检测）
#
# 参考：https://github.com/cli/cli

source "$HOME/.bash/installer/_common.sh"

# ---------------------------------------------------------------------------
# 1. 检测操作系统与架构
#   gh 资产命名：gh_<ver>_<os>_<arch>.tar.gz
#   macOS 标签为 macOS（注意大写），Linux 标签为 linux；架构为 amd64 / arm64
# ---------------------------------------------------------------------------
_i_detect_os "macOS" "linux" || return 1
_i_detect_arch "amd64" "arm64" || return 1

# ---------------------------------------------------------------------------
# 2. 配置
# ---------------------------------------------------------------------------
_i_setup "gh" "cli/cli" "v2.80.0" "GH_VERSION"
[ -n "${GH_INSTALL_DIR:-}" ] && _i_set_install_dir "$GH_INSTALL_DIR"
[ -n "${GH_VERSION:-}" ] && _I_VERSION="$GH_VERSION"

# ---------------------------------------------------------------------------
# 3. 已安装检查
# ---------------------------------------------------------------------------
_i_check_installed "gh" "--version" || return 0

# ---------------------------------------------------------------------------
# 4. 下载（续传检测 → 版本检测 → 归档复用 → 下载）
#   Release 归档名: gh_<ver>_<os>_<arch>.tar.gz
# ---------------------------------------------------------------------------
_i_github_download "gh_${_I_OS}_${_I_ARCH}.tar.gz" \
    "https://github.com/cli/cli/releases/download/<tag>/gh_<ver>_${_I_OS}_${_I_ARCH}.tar.gz" ||
    return 1

# ---------------------------------------------------------------------------
# 5. 解压 & 安装
#   归档内为 gh_<ver>_<os>_<arch>/bin/gh，剥离 2 层后 gh 位于临时目录根
# ---------------------------------------------------------------------------
_i_extract 2 || return 1
_i_install_one "gh" || return 1

# ---------------------------------------------------------------------------
# 6. 验证安装
# ---------------------------------------------------------------------------
_i_verify "${_I_INSTALL_DIR}/gh" "--version" || {
    echo "[错误] gh 安装后无法执行，请检查" >&2
    return 1
}
_i_path_warning "gh"
_i_cleanup
